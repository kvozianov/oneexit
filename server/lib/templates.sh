#!/usr/bin/env bash
# Configuration templates for the oneexit server, as pure bash functions so
# that --dry-run can print exactly what would be written.

# render_unbound_conf [TRUST_ANCHOR]
# Recursive resolver bound to the tunnel address only. It does not conflict
# with systemd-resolved (127.0.0.53:53) or any other resolver on the host,
# because only 10.66.0.1 is bound. TRUST_ANCHOR=no omits the
# auto-trust-anchor-file line when the distribution already configures it
# (Debian and Ubuntu ship root-auto-trust-anchor-file.conf); DNSSEC stays on.
render_unbound_conf() {
  local trust_anchor="${1:-yes}" anchor_line
  if [[ "${trust_anchor}" == "no" ]]; then
    anchor_line='    # DNSSEC trust anchor (/var/lib/unbound/root.key) is already set by the distribution config.'
  else
    anchor_line='    auto-trust-anchor-file: "/var/lib/unbound/root.key"'
  fi
  cat <<CONF
# oneexit: recursive DNS for WireGuard peers (generated by server/install.sh; do not edit)
server:
    # Listen on the tunnel address only. ip-freebind lets unbound start
    # before wg0 is up at boot.
    interface: 10.66.0.1
    port: 53
    ip-freebind: yes
    do-ip4: yes
    do-ip6: no
    do-udp: yes
    do-tcp: yes

    # Answer WireGuard peers only.
    access-control: 0.0.0.0/0 refuse
    access-control: 10.66.0.0/24 allow

    # Privacy and hardening.
    hide-identity: yes
    hide-version: yes
    qname-minimisation: yes
    harden-glue: yes
    harden-dnssec-stripped: yes
    prefetch: yes

    # DNSSEC validation.
${anchor_line}
CONF
}

# render_nftables_conf PORT IFACE
# Only our own tables (inet oneexit, ip oneexit_nat) are touched. The
# "table X / delete table X / table X { ... }" sequence makes `nft -f` on this
# file idempotent: the empty declaration creates the table if it is missing,
# the delete removes it with all old rules, and the block recreates it, all in
# one atomic transaction. Unrelated tables (ufw, docker, ...) are left alone.
render_nftables_conf() {
  local port="$1" iface="$2"
  cat <<CONF
#!/usr/sbin/nft -f
# oneexit firewall and NAT (generated by server/install.sh; do not edit)
# Loaded by oneexit-nft.service (at boot and by install.sh). Only the two
# oneexit tables are replaced; the rest of the ruleset is left alone.

table inet oneexit
delete table inet oneexit
table inet oneexit {
    chain input {
        type filter hook input priority 0; policy accept;
        udp dport ${port} accept
        iifname "wg0" ip saddr 10.66.0.0/24 udp dport 53 accept
        iifname "wg0" ip saddr 10.66.0.0/24 tcp dport 53 accept
    }

    chain forward {
        type filter hook forward priority 0; policy accept;
        iifname "wg0" ip saddr 10.66.0.0/24 accept
        oifname "wg0" ct state established,related accept
    }
}

table ip oneexit_nat
delete table ip oneexit_nat
table ip oneexit_nat {
    chain postrouting {
        type nat hook postrouting priority 100; policy accept;
        ip saddr 10.66.0.0/24 oifname "${iface}" masquerade
    }
}
CONF
}

# render_nft_unit
# Oneshot unit that loads our tables at boot without `flush ruleset`, so rules
# of other tools (ufw, docker) survive. Stopping it deletes only our tables.
render_nft_unit() {
  cat <<'UNIT'
# oneexit firewall and NAT (generated by server/install.sh; do not edit)
[Unit]
Description=oneexit WireGuard firewall and NAT (nftables tables inet oneexit, ip oneexit_nat)
After=network-pre.target
Wants=network-pre.target
Before=wg-quick@wg0.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f /etc/nftables.d/oneexit.nft
ExecStop=-/usr/sbin/nft delete table inet oneexit
ExecStop=-/usr/sbin/nft delete table ip oneexit_nat

[Install]
WantedBy=multi-user.target
UNIT
}

# render_sysctl_conf
render_sysctl_conf() {
  cat <<'CONF'
# oneexit: forward traffic from WireGuard peers (generated by server/install.sh)
net.ipv4.ip_forward=1
CONF
}
